"""Research Report Generation service producing Markdown and PDF reports with ReportLab."""
import os
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Any, List
from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable

from app.core.config import settings

class ReportGenerator:
    """Synthesizes structured research reports with Markdown and PDF export."""

    @classmethod
    def generate_markdown(cls, report_data: Dict[str, Any]) -> str:
        """Format report into clean scientific Markdown."""
        lines = [
            f"# EvidenceGraph AI Research Report",
            f"**Title**: {report_data.get('title', 'Investigation Report')}",
            f"**Research Question**: *{report_data.get('research_question')}*",
            f"**Generated**: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M:%S UTC')}",
            "",
            "---",
            "",
            "## 1. Executive Summary",
            report_data.get("executive_summary", "No summary provided."),
            "",
            "## 2. Key Findings",
        ]

        for finding in report_data.get("key_findings", []):
            lines.append(f"- {finding}")

        lines.extend([
            "",
            "## 3. Supporting Evidence",
        ])

        for ev in report_data.get("supporting_evidence", []):
            doc = ev.get("document_name", "Document")
            pg = ev.get("page_number", "?")
            claim = ev.get("claim", "")
            lines.append(f"- **{doc}** (Page {pg}): {claim}")

        lines.extend([
            "",
            "## 4. Contradictory & Divergent Findings",
        ])

        contradictions = report_data.get("contradictory_findings", [])
        if contradictions:
            for c in contradictions:
                lines.append(f"- **[{c.get('type', 'CONFLICT')}]**: {c.get('explanation', '')}")
        else:
            lines.append("No direct contradictions detected among the evaluated sources.")

        lines.extend([
            "",
            "## 5. Research Limitations",
            report_data.get("limitations", "Synthesized from currently uploaded project documents."),
            "",
            "## 6. Traceable References",
        ])

        for ref in report_data.get("references", []):
            lines.append(f"- [{ref.get('citation_id', '-')}] **{ref.get('document_name', 'Doc')}**, Page {ref.get('page_number', '?')}: *\"{ref.get('exact_passage', '')[:120]}...\"*")

        lines.extend([
            "",
            "## 7. Conclusion",
            report_data.get("conclusion", "Investigation completed."),
            "",
            "---",
            "*Report generated by EvidenceGraph AI - Grounded Research Platform*"
        ])

        return "\n".join(lines)

    @classmethod
    def generate_pdf(cls, report_data: Dict[str, Any], output_filename: str) -> str:
        """Generate formatted publication-quality PDF using ReportLab."""
        reports_dir = Path(settings.UPLOAD_DIR) / "reports"
        reports_dir.mkdir(parents=True, exist_ok=True)
        pdf_path = reports_dir / output_filename

        doc = SimpleDocTemplate(
            str(pdf_path),
            pagesize=letter,
            rightMargin=54,
            leftMargin=54,
            topMargin=54,
            bottomMargin=54
        )

        styles = getSampleStyleSheet()
        
        # Custom Typography
        title_style = ParagraphStyle(
            'ReportTitle',
            parent=styles['Heading1'],
            fontSize=22,
            leading=26,
            textColor=colors.HexColor('#0f172a'),
            spaceAfter=10
        )
        subtitle_style = ParagraphStyle(
            'ReportSubtitle',
            parent=styles['Normal'],
            fontSize=11,
            leading=14,
            textColor=colors.HexColor('#64748b'),
            spaceAfter=15
        )
        h2_style = ParagraphStyle(
            'ReportH2',
            parent=styles['Heading2'],
            fontSize=14,
            leading=18,
            textColor=colors.HexColor('#1e293b'),
            spaceBefore=14,
            spaceAfter=8
        )
        body_style = ParagraphStyle(
            'ReportBody',
            parent=styles['Normal'],
            fontSize=10,
            leading=14,
            textColor=colors.HexColor('#334155'),
            spaceAfter=8
        )

        elements = []

        # Header Title
        elements.append(Paragraph("EvidenceGraph AI Research Intelligence Report", title_style))
        elements.append(Paragraph(f"Question: {report_data.get('research_question')}", subtitle_style))
        elements.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#cbd5e1'), spaceAfter=15))

        # Executive Summary
        elements.append(Paragraph("1. Executive Summary", h2_style))
        elements.append(Paragraph(report_data.get("executive_summary", ""), body_style))
        elements.append(Spacer(1, 10))

        # Key Findings
        elements.append(Paragraph("2. Key Findings", h2_style))
        for finding in report_data.get("key_findings", []):
            elements.append(Paragraph(f"• {finding}", body_style))
        elements.append(Spacer(1, 10))

        # Evidence Summary Table
        elements.append(Paragraph("3. Supporting Evidence & Citations", h2_style))
        table_data = [["Source Document", "Page", "Evidence Statement"]]
        for ev in report_data.get("supporting_evidence", [])[:8]:
            table_data.append([
                ev.get("document_name", "Doc")[:25],
                str(ev.get("page_number", "-")),
                Paragraph(ev.get("claim", "")[:150], body_style)
            ])

        evidence_table = Table(table_data, colWidths=[150, 45, 305])
        evidence_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#f1f5f9')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.HexColor('#0f172a')),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 9),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
            ('TOPPADDING', (0, 0), (-1, -1), 6),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e2e8f0')),
        ]))
        elements.append(evidence_table)
        elements.append(Spacer(1, 15))

        # Conclusion
        elements.append(Paragraph("4. Conclusion & Limitations", h2_style))
        elements.append(Paragraph(report_data.get("conclusion", ""), body_style))
        elements.append(Paragraph(f"<b>Limitations:</b> {report_data.get('limitations', '')}", body_style))

        # Build PDF
        doc.build(elements)
        return str(pdf_path)
